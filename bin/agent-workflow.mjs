#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { normalizeManagedPath, resolveManagedPath } from '../lib/path-policy.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, '..');
const manifestRelativePath = 'docs/.agent-workflow-install.json';
const activeTaskRelativePath = 'docs/agent-tasks/ACTIVE_TASK.json';
const activeTaskCompanionRelativePath = 'docs/agent-tasks/ACTIVE_TASK.md';
const resultDirectoryPrefix = 'docs/agent-results/';
const validModes = new Set(['IMPLEMENT', 'TEST_ONLY', 'REVIEW_ONLY']);

function fail(message, code = 1) {
  console.error(`agent-workflow: ${message}`);
  process.exit(code);
}

function readText(file) {
  return fs.readFileSync(file, 'utf8');
}

function readJson(file) {
  return JSON.parse(readText(file));
}

function ensureRelativeSafe(rel) {
  try {
    return normalizeManagedPath(rel, { allowGlob: true });
  } catch (error) {
    fail(error.message);
  }
}

function managedAbsolute(target, rel) {
  try {
    return resolveManagedPath(target, rel);
  } catch (error) {
    fail(error.message);
  }
}

function unique(values) {
  return [...new Set(values)];
}

function detectPackageManager(target) {
  if (fs.existsSync(path.join(target, 'pnpm-lock.yaml'))) return 'pnpm';
  if (fs.existsSync(path.join(target, 'yarn.lock'))) return 'yarn';
  if (fs.existsSync(path.join(target, 'bun.lockb')) || fs.existsSync(path.join(target, 'bun.lock'))) return 'bun';
  if (fs.existsSync(path.join(target, 'package-lock.json'))) return 'npm';
  return null;
}

function packageScriptCommand(manager, script) {
  if (manager === 'yarn') return `yarn ${script}`;
  if (manager === 'bun') return `bun run ${script}`;
  if (manager === 'pnpm') return `pnpm ${script === 'test' ? 'test' : `run ${script}`}`;
  return script === 'test' ? 'npm test' : `npm run ${script}`;
}

function detectProject(target) {
  const facts = {
    languages: [],
    package_manager: null,
    build_command: null,
    test_command: null,
    ci: []
  };

  const has = (rel) => fs.existsSync(path.join(target, rel));
  if (has('tsconfig.json')) facts.languages.push('TypeScript');
  if (has('package.json')) {
    facts.languages.push('JavaScript');
    try {
      const pkg = readJson(path.join(target, 'package.json'));
      if (typeof pkg.packageManager === 'string') facts.package_manager = pkg.packageManager.split('@')[0];
      facts.package_manager ??= detectPackageManager(target);
      const manager = facts.package_manager ?? 'npm';
      if (pkg.scripts?.build) facts.build_command = packageScriptCommand(manager, 'build');
      if (pkg.scripts?.test) facts.test_command = packageScriptCommand(manager, 'test');
    } catch {
      // Keep detection conservative if package.json is malformed.
    }
  }
  if (has('pyproject.toml') || has('requirements.txt')) facts.languages.push('Python');
  if (has('go.mod')) facts.languages.push('Go');
  if (has('Cargo.toml')) facts.languages.push('Rust');
  facts.languages = unique(facts.languages);
  facts.package_manager ??= detectPackageManager(target);

  const workflows = path.join(target, '.github', 'workflows');
  if (fs.existsSync(workflows) && fs.statSync(workflows).isDirectory()) {
    facts.ci = fs.readdirSync(workflows)
      .filter((name) => /\.ya?ml$/i.test(name))
      .sort()
      .map((name) => `.github/workflows/${name}`);
  }
  return facts;
}

function projectSection(facts) {
  const languages = facts.languages.length ? facts.languages.join(', ') : 'not confidently detected';
  const ci = facts.ci.length ? facts.ci.join(', ') : 'not detected';
  return `\n\n## Generated project adapter\n\nThis section was generated by the agent-workflow installer. Treat detected values as repository facts to verify, never as permission to invent missing commands.\n\n- Languages: ${languages}\n- Package manager: ${facts.package_manager ?? 'not detected'}\n- Build command: ${facts.build_command ?? 'not detected; do not invent one'}\n- Test command: ${facts.test_command ?? 'not detected; do not invent one'}\n- CI: ${ci}\n\nTask permissions still come only from the active Task Contract. Executor choice does not change permissions.\n`;
}

function copyPlan(facts) {
  return [
    ['templates/agent-workflow.md', 'docs/agent-workflow.md', projectSection(facts)],
    ['templates/agent-short-triggers.md', 'docs/agent-short-triggers.md', ''],
    ['templates/agent-tasks/README.md', 'docs/agent-tasks/README.md', ''],
    ['templates/agent-tasks/TEMPLATE_TASK.json', 'docs/agent-tasks/TEMPLATE_TASK.json', ''],
    ['templates/agent-tasks/TEMPLATE_IMPLEMENT.md', 'docs/agent-tasks/TEMPLATE_IMPLEMENT.md', ''],
    ['templates/agent-tasks/TEMPLATE_TEST_ONLY.md', 'docs/agent-tasks/TEMPLATE_TEST_ONLY.md', ''],
    ['templates/agent-tasks/TEMPLATE_REVIEW_ONLY.md', 'docs/agent-tasks/TEMPLATE_REVIEW_ONLY.md', ''],
    ['templates/agent-results/README.md', 'docs/agent-results/README.md', ''],
    ['schema/task-contract.schema.json', '.agent-workflow/schema/task-contract.schema.json', ''],
    ['schema/result-contract.schema.json', '.agent-workflow/schema/result-contract.schema.json', ''],
    ['validator/validate-contract.mjs', '.agent-workflow/validator/validate-contract.mjs', ''],
    ['lib/path-policy.mjs', '.agent-workflow/lib/path-policy.mjs', '']
  ].map(([source, destination, suffix]) => ({
    source: path.join(packageRoot, source),
    destination: ensureRelativeSafe(destination),
    suffix
  }));
}

function parentDirectories(rel) {
  const dirs = [];
  let current = path.posix.dirname(rel);
  while (current && current !== '.') {
    dirs.push(ensureRelativeSafe(current));
    current = path.posix.dirname(current);
  }
  return dirs;
}

function install(targetArg) {
  const target = path.resolve(targetArg ?? process.cwd());
  if (!fs.existsSync(target) || !fs.statSync(target).isDirectory()) fail(`target directory does not exist: ${target}`);

  const manifestPath = path.join(target, manifestRelativePath);
  if (fs.existsSync(manifestPath)) fail(`workflow is already installed (${manifestRelativePath} exists)`);

  const facts = detectProject(target);
  const plan = copyPlan(facts);
  const missingSources = plan.filter((item) => !fs.existsSync(item.source));
  if (missingSources.length) fail(`package is incomplete; missing source: ${missingSources[0].source}`);

  const conflicts = plan.map((item) => item.destination).filter((rel) => fs.existsSync(managedAbsolute(target, rel)));
  if (conflicts.length) fail(`refusing to overwrite pre-existing files:\n- ${conflicts.join('\n- ')}`);

  const allDestinations = [...plan.map((item) => item.destination), manifestRelativePath];
  const generatedDirs = unique(allDestinations.flatMap(parentDirectories))
    .filter((rel) => !fs.existsSync(path.join(target, rel)))
    .sort((a, b) => a.split('/').length - b.split('/').length);

  for (const item of plan) {
    const destination = managedAbsolute(target, item.destination);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, readText(item.source) + item.suffix, 'utf8');
  }

  const version = readText(path.join(packageRoot, 'VERSION')).trim();
  const manifest = {
    schema_version: 1,
    source_repository: 'Ran-sh/chatgpt_workflow',
    workflow_version: version,
    project: path.basename(target),
    installed_at: new Date().toISOString(),
    generated_files: [...plan.map((item) => item.destination), manifestRelativePath],
    generated_dirs: generatedDirs,
    project_facts: facts
  };

  const safeManifestPath = managedAbsolute(target, manifestRelativePath);
  fs.mkdirSync(path.dirname(safeManifestPath), { recursive: true });
  fs.writeFileSync(safeManifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  console.log(`Installed Agent Workflow ${version} into ${target}`);
  console.log(`Managed files: ${manifest.generated_files.length}`);
  console.log('No ACTIVE task was created.');
}

function validatorPath() {
  return path.join(packageRoot, 'validator', 'validate-contract.mjs');
}

function runValidator(kind, file, stdio = 'inherit') {
  return spawnSync(process.execPath, [validatorPath(), kind, file], {
    stdio,
    encoding: stdio === 'inherit' ? undefined : 'utf8'
  });
}

function validate(kind, fileArg) {
  if (kind === 'handoff') {
    const result = spawnSync(process.execPath, [validatorPath(), 'handoff', ...process.argv.slice(4)], {
      stdio: 'inherit'
    });
    process.exit(result.status ?? 1);
  }
  if (!['task', 'result'].includes(kind)) fail('validate requires kind: task, result, or handoff');
  if (!fileArg) fail('validate requires a contract file path');
  const file = path.resolve(fileArg);
  if (!fs.existsSync(file)) fail(`contract file does not exist: ${file}`);
  const result = runValidator(kind, file, 'inherit');
  process.exit(result.status ?? 1);
}

function gitValue(target, args) {
  const result = spawnSync('git', ['-C', target, ...args], { encoding: 'utf8' });
  if (result.status !== 0) return null;
  const value = result.stdout.trim();
  return value || null;
}

function generatedTaskId() {
  return `TASK-${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}`;
}

function parseTaskOptions(args) {
  const options = {
    allow: [],
    forbid: [],
    validate: [],
    accept: [],
    complete: [],
    companion: false
  };
  const scalar = new Map([
    ['--target', 'target'],
    ['--id', 'id'],
    ['--mode', 'mode'],
    ['--source-branch', 'sourceBranch'],
    ['--source-commit', 'sourceCommit'],
    ['--objective', 'objective'],
    ['--context', 'context'],
    ['--result', 'result']
  ]);
  const repeated = new Map([
    ['--allow', 'allow'],
    ['--forbid', 'forbid'],
    ['--validate', 'validate'],
    ['--accept', 'accept'],
    ['--complete', 'complete']
  ]);

  for (let i = 0; i < args.length; i += 1) {
    const token = args[i];
    if (token === '--companion') {
      options.companion = true;
      continue;
    }
    const scalarKey = scalar.get(token);
    const repeatedKey = repeated.get(token);
    if (!scalarKey && !repeatedKey) fail(`unknown task create option: ${token}`);
    const value = args[i + 1];
    if (!value || value.startsWith('--')) fail(`${token} requires a value`);
    if (scalarKey) options[scalarKey] = value;
    else options[repeatedKey].push(value);
    i += 1;
  }
  return options;
}

function defaultForbidden(mode) {
  if (mode === 'TEST_ONLY' || mode === 'REVIEW_ONLY') {
    return ['source code', 'existing tests', 'build scripts', 'CI configuration', 'package or release metadata'];
  }
  return ['secrets and credentials', 'unrelated files outside allowed_changes', 'workflow protocol or installation metadata unless explicitly allowed'];
}

function taskCompanion(contract) {
  return `# Active Task — Human Companion\n\n> Non-authoritative view. The machine-readable \`ACTIVE_TASK.json\` is the source of truth.\n\n- ID: \`${contract.id}\`\n- Mode: \`${contract.mode}\`\n- Source: \`${contract.source_branch}@${contract.source_commit}\`\n- Result Contract: \`${contract.result_contract}\`\n\n## Objective\n\n${contract.objective}\n\n## Context\n\n${contract.context || '(none)'}\n\n## Allowed Changes\n\n${contract.allowed_changes.map((item) => `- ${item}`).join('\n')}\n\n## Forbidden Changes\n\n${contract.forbidden_changes.map((item) => `- ${item}`).join('\n')}\n\n## Validation\n\n${contract.validation.map((item) => `- ${item}`).join('\n')}\n\n## Acceptance Criteria\n\n${contract.acceptance_criteria.map((item) => `- ${item}`).join('\n')}\n`;
}

function taskCreate(args) {
  const options = parseTaskOptions(args);
  const target = path.resolve(options.target ?? process.cwd());
  if (!fs.existsSync(target) || !fs.statSync(target).isDirectory()) fail(`target directory does not exist: ${target}`);
  if (!fs.existsSync(path.join(target, 'docs', 'agent-workflow.md'))) {
    fail('target does not appear to have Agent Workflow installed (docs/agent-workflow.md is missing)');
  }

  const mode = String(options.mode ?? '').toUpperCase();
  if (!validModes.has(mode)) fail('task create requires --mode IMPLEMENT, TEST_ONLY, or REVIEW_ONLY');
  if (!options.objective) fail('task create requires --objective');
  if (!options.validate.length) fail('task create requires at least one --validate; do not invent validation commands');
  if (!options.accept.length) fail('task create requires at least one --accept');

  const id = options.id ?? generatedTaskId();
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id)) fail('task id may contain only letters, numbers, dot, underscore, and hyphen');

  const outputRel = activeTaskRelativePath;
  const output = managedAbsolute(target, outputRel);
  const companionRel = activeTaskCompanionRelativePath;
  const companion = managedAbsolute(target, companionRel);

  if (fs.existsSync(output) || fs.existsSync(companion)) {
    fail('an ACTIVE task already exists; complete or intentionally remove it before creating another');
  }

  const sourceBranch = options.sourceBranch ?? gitValue(target, ['rev-parse', '--abbrev-ref', 'HEAD']);
  const preparedFromCommit = gitValue(target, ['rev-parse', 'HEAD']);
  const sourceCommit = options.sourceCommit ?? 'LATEST';
  if (!sourceBranch || sourceBranch === 'HEAD') fail('cannot determine source branch; pass --source-branch explicitly');

  const resultContract = ensureRelativeSafe(options.result ?? `${resultDirectoryPrefix}${id}-result.json`);
  if (!resultContract.startsWith(resultDirectoryPrefix)) fail(`result contract must be under ${resultDirectoryPrefix}`);

  const explicitAllowed = unique(options.allow.map(ensureRelativeSafe));
  if (mode === 'IMPLEMENT' && !explicitAllowed.length) fail('IMPLEMENT tasks require at least one --allow path');
  if (mode === 'TEST_ONLY' || mode === 'REVIEW_ONLY') {
    for (const item of explicitAllowed) {
      if (!item.startsWith(resultDirectoryPrefix)) fail(`${mode} --allow paths must be under ${resultDirectoryPrefix}`);
    }
  }
  const allowedChanges = unique([...explicitAllowed, resultContract]);

  const forbiddenChanges = unique(options.forbid.length ? options.forbid : defaultForbidden(mode));
  let completionContract = unique(options.complete.length ? options.complete.map(ensureRelativeSafe) : allowedChanges);
  completionContract = unique([
    ...completionContract,
    resultContract,
    activeTaskRelativePath,
    ...(options.companion ? [activeTaskCompanionRelativePath] : [])
  ]);

  const version = readText(path.join(packageRoot, 'VERSION')).trim();
  const contract = {
    id,
    mode,
    source_branch: sourceBranch,
    source_commit: sourceCommit,
    objective: options.objective,
    context: options.context ?? '',
    allowed_changes: allowedChanges,
    forbidden_changes: forbiddenChanges,
    validation: unique(options.validate),
    acceptance_criteria: unique(options.accept),
    result_contract: resultContract,
    completion_commit_contract: completionContract,
    delete_active_task_on_completion: true,
    metadata: {
      executor: 'ANY',
      generator: `agent-workflow@${version}`,
      generated_at: new Date().toISOString(),
      companion: options.companion,
      prepared_from_commit: preparedFromCommit,
      attempt: 1
    }
  };

  fs.mkdirSync(path.dirname(output), { recursive: true });
  const temp = `${output}.tmp-${process.pid}`;
  fs.writeFileSync(temp, `${JSON.stringify(contract, null, 2)}\n`, 'utf8');
  const check = runValidator('task', temp, 'pipe');
  if (check.status !== 0) {
    fs.rmSync(temp, { force: true });
    const detail = (check.stderr || check.stdout || '').trim();
    fail(`generated Task Contract failed validation${detail ? `:\n${detail}` : ''}`);
  }
  fs.renameSync(temp, output);

  if (options.companion) fs.writeFileSync(companion, taskCompanion(contract), 'utf8');

  console.log(`Created ${outputRel}`);
  if (options.companion) console.log(`Created ${companionRel} (non-authoritative companion)`);
  console.log(`Task ID: ${id}`);
  console.log(`Mode: ${mode}`);
  console.log(`Source: ${sourceBranch}@${sourceCommit}`);
  console.log('Executor: ANY');
}

function taskResume(args) {
  let target = process.cwd();
  let sourceCommit;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === '--target' && args[index + 1]) {
      target = path.resolve(args[index + 1]);
      index += 1;
    } else if (args[index] === '--source-commit' && args[index + 1]) {
      sourceCommit = args[index + 1];
      index += 1;
    } else {
      fail(`unknown task resume option: ${args[index]}`);
    }
  }

  const taskPath = managedAbsolute(target, activeTaskRelativePath);
  if (!fs.existsSync(taskPath)) fail(`no ACTIVE task found at ${activeTaskRelativePath}`);
  if (runValidator('task', taskPath, 'pipe').status !== 0) fail('ACTIVE task is invalid');
  const task = readJson(taskPath);
  const oldResult = task.result_contract;
  const oldResultPath = managedAbsolute(target, oldResult);
  if (!fs.existsSync(oldResultPath)) fail(`blocked result does not exist: ${oldResult}`);
  if (runValidator('result', oldResultPath, 'pipe').status !== 0) fail('blocked Result Contract is invalid');
  const handoff = spawnSync(process.execPath, [
    validatorPath(), 'handoff', '--task', taskPath, '--result', oldResultPath, '--target', target
  ], { encoding: 'utf8' });
  if (handoff.status !== 0) {
    fail(`blocked Result Contract does not match the ACTIVE task: ${(handoff.stderr || handoff.stdout || '').trim()}`);
  }
  const result = readJson(oldResultPath);
  if (result.task_id !== task.id) fail('blocked result task_id does not match ACTIVE task');
  if (result.status !== 'BLOCKED') fail('task resume requires the current Result Contract status to be BLOCKED');

  const attempt = Number.isInteger(task.metadata?.attempt) ? task.metadata.attempt + 1 : 2;
  const newResult = ensureRelativeSafe(`${resultDirectoryPrefix}${task.id}-attempt-${attempt}-result.json`);
  if (fs.existsSync(managedAbsolute(target, newResult))) fail(`resume result already exists: ${newResult}`);
  const replaceResult = (items) => unique(items.map((item) => item === oldResult ? newResult : item));
  task.result_contract = newResult;
  task.allowed_changes = replaceResult(task.allowed_changes);
  task.completion_commit_contract = replaceResult(task.completion_commit_contract);
  task.source_commit = sourceCommit ?? task.source_commit;
  task.metadata = {
    ...(task.metadata ?? {}),
    attempt,
    resumed_from: oldResult,
    resumed_at: new Date().toISOString()
  };

  const temporary = `${taskPath}.tmp-${process.pid}`;
  fs.writeFileSync(temporary, `${JSON.stringify(task, null, 2)}\n`, 'utf8');
  const check = runValidator('task', temporary, 'pipe');
  if (check.status !== 0) {
    fs.rmSync(temporary, { force: true });
    fail(`resumed Task Contract failed validation: ${(check.stderr || check.stdout || '').trim()}`);
  }
  fs.renameSync(temporary, taskPath);
  if (task.metadata.companion === true) {
    const companionPath = managedAbsolute(target, activeTaskCompanionRelativePath);
    const companionTemporary = `${companionPath}.tmp-${process.pid}`;
    fs.writeFileSync(companionTemporary, taskCompanion(task), 'utf8');
    fs.renameSync(companionTemporary, companionPath);
  }
  console.log(`Resumed ${task.id} as attempt ${attempt}`);
  console.log(`Preserved ${oldResult}`);
  console.log(`Next result: ${newResult}`);
}

function hasActiveTask(target) {
  return [activeTaskRelativePath, activeTaskCompanionRelativePath]
    .filter((rel) => fs.existsSync(managedAbsolute(target, rel)));
}

function parseTargetJsonOptions(args) {
  let target = process.cwd();
  let json = false;
  for (let index = 0; index < args.length; index += 1) {
    const option = args[index];
    if (option === '--json') {
      json = true;
    } else if (option === '--target' && args[index + 1]) {
      target = path.resolve(args[index + 1]);
      index += 1;
    } else {
      fail(`unknown option: ${option}`);
    }
  }
  return { target, json };
}

function doctor(args) {
  const { target, json } = parseTargetJsonOptions(args);
  const manifestPath = managedAbsolute(target, manifestRelativePath);
  const taskPath = managedAbsolute(target, activeTaskRelativePath);
  const installation = { installed: fs.existsSync(manifestPath), valid: false };
  if (installation.installed) {
    try {
      const manifest = readJson(manifestPath);
      const installedFiles = Array.isArray(manifest.generated_files) ? manifest.generated_files : [];
      installation.valid = manifest.source_repository === 'Ran-sh/chatgpt_workflow'
        && manifest.workflow_version === readText(path.join(packageRoot, 'VERSION')).trim()
        && installedFiles.length > 0
        && installedFiles.every((rel) => fs.existsSync(managedAbsolute(target, rel)))
        && fs.existsSync(managedAbsolute(target, '.agent-workflow/validator/validate-contract.mjs'))
        && fs.existsSync(managedAbsolute(target, '.agent-workflow/lib/path-policy.mjs'));
      installation.workflow_version = manifest.workflow_version ?? null;
    } catch {
      installation.valid = false;
    }
  }

  const activeTask = { present: fs.existsSync(taskPath), valid: null };
  if (activeTask.present) {
    activeTask.valid = runValidator('task', taskPath, 'pipe').status === 0;
  }

  const isGitRepository = gitValue(target, ['rev-parse', '--is-inside-work-tree']) === 'true';
  const worktree = {
    is_git_repository: isGitRepository,
    clean: isGitRepository ? gitValue(target, ['status', '--porcelain']) === null : null,
    branch: isGitRepository ? gitValue(target, ['rev-parse', '--abbrev-ref', 'HEAD']) : null,
    commit: isGitRepository ? gitValue(target, ['rev-parse', 'HEAD']) : null
  };
  const report = {
    ok: installation.valid && (!activeTask.present || activeTask.valid === true),
    installation,
    active_task: activeTask,
    worktree
  };

  if (json) console.log(JSON.stringify(report, null, 2));
  else {
    console.log(`Installation: ${installation.valid ? 'VALID' : installation.installed ? 'INVALID' : 'MISSING'}`);
    console.log(`Active task: ${activeTask.present ? activeTask.valid ? 'VALID' : 'INVALID' : 'NONE'}`);
    console.log(`Worktree: ${isGitRepository ? worktree.clean ? 'CLEAN' : 'DIRTY' : 'NOT A GIT REPOSITORY'}`);
  }
  process.exit(report.ok ? 0 : 1);
}

function status(args) {
  const { target, json } = parseTargetJsonOptions(args);
  const manifestPath = managedAbsolute(target, manifestRelativePath);
  const taskPath = managedAbsolute(target, activeTaskRelativePath);
  const report = { state: 'UNINSTALLED', task_id: null, result_path: null, observed_result_commit: null };

  if (fs.existsSync(manifestPath)) {
    try {
      const manifest = readJson(manifestPath);
      const installedFiles = Array.isArray(manifest.generated_files) ? manifest.generated_files : [];
      const installationValid = manifest.source_repository === 'Ran-sh/chatgpt_workflow'
        && manifest.workflow_version === readText(path.join(packageRoot, 'VERSION')).trim()
        && installedFiles.length > 0
        && installedFiles.every((rel) => fs.existsSync(managedAbsolute(target, rel)));
      report.state = installationValid ? 'IDLE' : 'INVALID';
    } catch {
      report.state = 'INVALID';
    }
    if (report.state === 'INVALID') {
      if (json) console.log(JSON.stringify(report, null, 2));
      else console.log(`Workflow state: ${report.state}`);
      process.exit(1);
    }
    if (fs.existsSync(taskPath)) {
      if (runValidator('task', taskPath, 'pipe').status !== 0) {
        report.state = 'INVALID';
      } else {
        const task = readJson(taskPath);
        report.task_id = task.id;
        report.result_path = task.result_contract;
        const resultPath = managedAbsolute(target, task.result_contract);
        if (!fs.existsSync(resultPath)) {
          report.state = 'READY';
        } else if (runValidator('result', resultPath, 'pipe').status !== 0) {
          report.state = 'INVALID';
        } else {
          try {
            const result = readJson(resultPath);
            report.state = result.status === 'BLOCKED' ? 'BLOCKED' : 'RESULT_READY';
            report.observed_result_commit = gitValue(target, ['log', '-1', '--format=%H', '--', task.result_contract]);
          } catch {
            report.state = 'INVALID';
          }
        }
      }
    }
  }

  if (json) console.log(JSON.stringify(report, null, 2));
  else console.log(`Workflow state: ${report.state}`);
  process.exit(report.state === 'INVALID' ? 1 : 0);
}

function uninstall(targetArg) {
  const target = path.resolve(targetArg ?? process.cwd());
  const manifestPath = managedAbsolute(target, manifestRelativePath);
  if (!fs.existsSync(manifestPath)) fail(`no installation manifest found at ${manifestRelativePath}`);

  const active = hasActiveTask(target);
  if (active.length) fail(`refusing to uninstall while an ACTIVE task exists:\n- ${active.join('\n- ')}`);

  let manifest;
  try {
    manifest = readJson(manifestPath);
  } catch (error) {
    fail(`cannot parse installation manifest: ${error.message}`);
  }
  if (manifest.source_repository !== 'Ran-sh/chatgpt_workflow') fail('installation manifest does not identify Ran-sh/chatgpt_workflow');
  if (!Array.isArray(manifest.generated_files)) fail('installation manifest has no generated_files array');

  const managedAllowlist = new Set([
    ...copyPlan(detectProject(target)).map((item) => item.destination),
    manifestRelativePath
  ]);
  const unexpectedFiles = manifest.generated_files.filter((rel) => !managedAllowlist.has(ensureRelativeSafe(rel)));
  if (unexpectedFiles.length) fail(`installation manifest contains unmanaged files:\n- ${unexpectedFiles.join('\n- ')}`);

  const files = manifest.generated_files.map(ensureRelativeSafe);
  if (!files.includes(manifestRelativePath)) files.push(manifestRelativePath);

  const ordered = files.filter((rel) => rel !== manifestRelativePath);
  ordered.push(manifestRelativePath);
  for (const rel of ordered) {
    const absolute = managedAbsolute(target, rel);
    if (fs.existsSync(absolute) && fs.statSync(absolute).isFile()) fs.unlinkSync(absolute);
  }

  const allowedDirs = new Set([...managedAllowlist].flatMap(parentDirectories));
  const dirs = Array.isArray(manifest.generated_dirs) ? manifest.generated_dirs.map(ensureRelativeSafe) : [];
  const unexpectedDirs = dirs.filter((rel) => !allowedDirs.has(rel));
  if (unexpectedDirs.length) fail(`installation manifest contains unmanaged directories:\n- ${unexpectedDirs.join('\n- ')}`);
  dirs.sort((a, b) => b.split('/').length - a.split('/').length);
  for (const rel of dirs) {
    const absolute = managedAbsolute(target, rel);
    if (fs.existsSync(absolute) && fs.statSync(absolute).isDirectory() && fs.readdirSync(absolute).length === 0) fs.rmdirSync(absolute);
  }

  console.log(`Removed Agent Workflow managed files from ${target}`);
  console.log('Pre-existing and unmanaged project files/directories were not touched.');
}

function help() {
  console.log(`agent-workflow

Usage:
  agent-workflow install [target]
  agent-workflow task create [options]
  agent-workflow task resume [--target <dir>] [--source-commit <revision>]
  agent-workflow doctor [--target <dir>] [--json]
  agent-workflow status [--target <dir>] [--json]
  agent-workflow validate task <file>
  agent-workflow validate result <file>
  agent-workflow validate handoff --task <file> --result <file> [--target <dir>] [--json]
  agent-workflow uninstall [target]
  agent-workflow --version

Run task create with --mode, --objective, --validate and --accept. IMPLEMENT also requires --allow.
BLOCKED results keep the ACTIVE task; task resume preserves the old result and opens a new attempt.`);
}

const args = process.argv.slice(2);
if (args[0] === '--version' || args[0] === '-v') {
  console.log(readText(path.join(packageRoot, 'VERSION')).trim());
  process.exit(0);
}

switch (args[0]) {
  case 'install':
    install(args[1]);
    break;
  case 'task':
    if (args[1] === 'create') taskCreate(args.slice(2));
    else if (args[1] === 'resume') taskResume(args.slice(2));
    else fail('task requires subcommand: create or resume');
    break;
  case 'validate':
    validate(args[1], args[2]);
    break;
  case 'doctor':
    doctor(args.slice(1));
    break;
  case 'status':
    status(args.slice(1));
    break;
  case 'uninstall':
    uninstall(args[1]);
    break;
  case 'help':
  case '--help':
  case '-h':
  case undefined:
    help();
    break;
  default:
    fail(`unknown command: ${args[0]}\nRun agent-workflow --help for usage.`);
}
